"use client";

import { useState } from "react";
import { toast } from "sonner";
import { Dialog, DialogContent, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { useConsignees, useExportMutations, useLoaderOptions } from "@/lib/query/containers";
import type { ExportDetail } from "@/lib/data/containers";

/**
 * New Container (export management). The internal LAL reference is generated by the server. The physical container
 * number is NOT asked for here: the assigned loader confirms it from the yard. Only the loader is required.
 */
export function NewContainerDialog({ open, onOpenChange, onCreated }: { open: boolean; onOpenChange: (v: boolean) => void; onCreated: (containerId: string) => void }) {
  const loaders = useLoaderOptions(open);
  const consignees = useConsignees(null);
  const { createContainer } = useExportMutations();
  const [loaderId, setLoaderId] = useState<string | null>(null);
  const [consigneeId, setConsigneeId] = useState<string | null>(null);
  const [country, setCountry] = useState("");
  const [port, setPort] = useState("");
  const [trucking, setTrucking] = useState("");
  const [note, setNote] = useState("");
  const [requestId, setRequestId] = useState(() => crypto.randomUUID());
  const [error, setError] = useState<string | null>(null);

  const list = loaders.data ?? [];

  function reset() {
    setLoaderId(null);
    setConsigneeId(null);
    setCountry("");
    setPort("");
    setTrucking("");
    setNote("");
    setRequestId(crypto.randomUUID());
    setError(null);
  }

  function close(next: boolean) {
    if (!next) reset();
    onOpenChange(next);
  }

  async function save() {
    if (!loaderId) return;
    setError(null);
    try {
      const detail: ExportDetail = await createContainer.mutateAsync({
        loaderId, consigneeId, destinationCountry: country, destinationPort: port, truckingCompany: trucking, shippingNote: note, requestId,
      });
      toast.success(`Container ${detail.container.t_ref} created and assigned.`);
      close(false);
      onCreated(detail.container.id);
    } catch (err) {
      setError(err instanceof Error ? err.message : "The container was not created. Nothing was saved.");
    }
  }

  return (
    <Dialog open={open} onOpenChange={close}>
      <DialogContent className="max-h-[90dvh] overflow-y-auto sm:max-w-lg">
        <DialogHeader>
          <DialogTitle>New Container</DialogTitle>
        </DialogHeader>
        <div className="grid gap-3 text-sm sm:grid-cols-2">
          <div className="space-y-1.5 sm:col-span-2">
            <span className="font-medium">Assigned Container Loader <span className="text-destructive">*</span></span>
            <Select value={loaderId ?? ""} onValueChange={(v) => v && setLoaderId(v)} disabled={createContainer.isPending}>
              <SelectTrigger className="h-10 w-full" aria-label="Assigned Container Loader">
                <SelectValue placeholder={loaders.isPending ? "Loading loaders…" : "Choose an active loader"}>
                  {(v: string) => list.find((l) => l.id === v)?.name ?? "Choose an active loader"}
                </SelectValue>
              </SelectTrigger>
              <SelectContent>
                {list.map((l) => (
                  <SelectItem key={l.id} value={l.id}>{l.name}</SelectItem>
                ))}
              </SelectContent>
            </Select>
            {loaders.isSuccess && list.length === 0 && <p className="text-xs text-muted-foreground">No active Container Loader accounts. Add one under Users first.</p>}
          </div>
          <div className="space-y-1.5 sm:col-span-2">
            <span className="font-medium">Consignee (optional)</span>
            <Select value={consigneeId ?? ""} onValueChange={(v) => setConsigneeId(v || null)} disabled={createContainer.isPending}>
              <SelectTrigger className="h-10 w-full" aria-label="Consignee">
                <SelectValue placeholder="Choose later">{(v: string) => consignees.data?.find((c) => c.id === v)?.company ?? "Choose later"}</SelectValue>
              </SelectTrigger>
              <SelectContent>
                {(consignees.data ?? []).map((c) => (
                  <SelectItem key={c.id} value={c.id}>{c.company}</SelectItem>
                ))}
              </SelectContent>
            </Select>
          </div>
          <label className="space-y-1">
            <span className="font-medium">Destination country</span>
            <Input className="h-10" value={country} onChange={(e) => setCountry(e.target.value)} />
          </label>
          <label className="space-y-1">
            <span className="font-medium">Destination port</span>
            <Input className="h-10" value={port} onChange={(e) => setPort(e.target.value)} />
          </label>
          <label className="space-y-1">
            <span className="font-medium">Trucking company</span>
            <Input className="h-10" value={trucking} onChange={(e) => setTrucking(e.target.value)} />
          </label>
          <label className="space-y-1">
            <span className="font-medium">Shipping note</span>
            <Input className="h-10" value={note} onChange={(e) => setNote(e.target.value)} />
          </label>
          <p className="text-xs text-muted-foreground sm:col-span-2">The container number is confirmed later by the loader from the yard.</p>
          {error && <p role="alert" className="text-sm text-destructive sm:col-span-2">{error}</p>}
        </div>
        <DialogFooter className="flex flex-col gap-2 sm:flex-row">
          <Button className="h-11 w-full" disabled={!loaderId || createContainer.isPending} onClick={save}>
            {createContainer.isPending ? "Creating…" : "Create & Assign"}
          </Button>
          <Button variant="outline" className="h-11 w-full" onClick={() => close(false)}>Cancel</Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
